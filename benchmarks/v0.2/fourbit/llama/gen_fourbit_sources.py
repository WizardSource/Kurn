#!/usr/bin/env python3
"""ggml-cpu sources for the WS-B (fourbit) end-to-end measurement: the multi-format hook of
integration/llama.cpp (kurn_hook.h, unchanged) with the 4-bit formats, MXFP4 / NVFP4 and the
nibble-path configs chosen in config.json.

Writes into DIR (normally ggml/src/ggml-cpu/): kurn_<fmt>_gemv.c, kurn_<fmt>_vfy{2,4,8}.c,
kurn.h and kurn_dispatch.h. A verify kernel shares the GEMV's packed copy when the GEMV's
algorithm keys are legal for it (rows=1, cols 2..8); otherwise it gets its own packing.

    gen_fourbit_sources.py DIR [--config config.json]
"""

import argparse
import json
import os
import re

from kurn import spec
from kurn.kernels import generate, kernel
from kurn.toolchain import data_path

HERE = os.path.dirname(os.path.abspath(__file__))
GTYPES = {
    "q8_0": "GGML_TYPE_Q8_0",
    "q4_0": "GGML_TYPE_Q4_0",
    "iq4_nl": "GGML_TYPE_IQ4_NL",
    "q4_K": "GGML_TYPE_Q4_K",
    "mxfp4": "GGML_TYPE_MXFP4",
    "nvfp4": "GGML_TYPE_NVFP4",
}
SHORT = {"q8_0": "q8", "q4_0": "q40", "iq4_nl": "iq4nl", "q4_K": "q4k", "mxfp4": "mxfp4", "nvfp4": "nvfp4"}
VFY_COLS = (2, 4, 8)
ALGO = ("unpack", "correction", "scales", "accum")


def gen(fmt, op, keys, rename=None):
    c = spec.resolve({"op": op, "weights": fmt, "target": "avx512_vnni", **keys})
    src = generate(c)
    if rename:
        src = re.sub(rf"\b{rename[0]}(_prepare|_packed|_vbmi|_novbmi)?\b", lambda m: rename[1] + (m.group(1) or ""), src)
    return c, src


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--config", default=os.path.join(HERE, "config.json"))
    a = ap.parse_args()
    cfg = json.load(open(a.config))
    os.makedirs(a.dir, exist_ok=True)
    with open(data_path("kurn.h")) as fh:
        open(os.path.join(a.dir, "kurn.h"), "w").write(fh.read())
    rows = []
    for fmt, keys in cfg.items():
        if fmt.startswith("_"):
            continue
        c, src = gen(fmt, "gemv", keys)
        open(os.path.join(a.dir, f"kurn_{fmt}_gemv.c"), "w").write(src)
        s = SHORT[fmt]
        vkeys = {k: c[k] for k in ALGO} if c["layout"] == "i16" else {}
        shared = bool(vkeys)
        for cols in VFY_COLS:
            try:
                spec.resolve({"op": "verify", "weights": fmt, "target": "avx512_vnni", "layout": "i16", "rows": 1, "cols": cols, **vkeys})
            except spec.SpecError:
                shared = False
        vfy = []
        for cols in VFY_COLS:
            vk = dict(vkeys if shared else {}, layout="i16", rows=1, cols=cols)
            _, vsrc = gen(fmt, "verify", vk, (f"k{s}_vfy", f"k{s}_vfy{cols}"))
            open(os.path.join(a.dir, f"kurn_{fmt}_vfy{cols}.c"), "w").write(vsrc)
            vfy.append(f"k{s}_vfy{cols}")
        align = 32 if c["layout"] == "l32" or c["unpack"] == "pair" else 16
        rows.append((fmt, c, shared, vfy, align))
        print(fmt, {k: c[k] for k in ("layout", "rows", "prefetch", *ALGO)}, "shared" if shared else "separate verify packing")
    out = ["// Generated by kurn/benchmarks/v0.2/fourbit/llama/gen_fourbit_sources.py. Do not edit.", "#pragma once",
           "#include <stdint.h>", "typedef void *(*kurn_prep_fn)(const void *, int64_t, int64_t);",
           "typedef void (*kurn_gemv_fn)(const void *, const void *, float *, int64_t, int64_t, int64_t);",
           "typedef void (*kurn_vfy_fn)(const void *, const void *, float *, int64_t, int64_t, int64_t, int64_t, int64_t);"]  # fmt: skip
    for _fmt, c, _shared, vfy, _align in rows:
        e = kernel(c).entry
        out.append(f"void *{e}_prepare(const void *, int64_t, int64_t); "
                   f"void {e}_packed(const void *, const void *, float *, int64_t, int64_t, int64_t);")  # fmt: skip
        for v in vfy:
            out.append(f"void *{v}_prepare(const void *, int64_t, int64_t); "
                       f"void {v}_packed(const void *, const void *, float *, int64_t, int64_t, int64_t, int64_t, int64_t);")  # fmt: skip
    out.append("typedef struct { int type; int row_align; int shared; kurn_prep_fn gemv_prep; kurn_gemv_fn gemv; "
               "kurn_prep_fn vfy_prep; kurn_vfy_fn vfy[3]; } kurn_kernel;")  # fmt: skip
    out.append("static const int kurn_vfy_cols[3] = {2, 4, 8};")
    out.append("static const kurn_kernel kurn_kernels[] = {")
    for fmt, c, shared, vfy, align in rows:
        e = kernel(c).entry
        out.append(f"    {{ {GTYPES[fmt]}, {align}, {int(shared)}, {e}_prepare, {e}_packed, {vfy[0]}_prepare, "
                   f"{{ {', '.join(v + '_packed' for v in vfy)} }} }},")  # fmt: skip
    out.append("};")
    open(os.path.join(a.dir, "kurn_dispatch.h"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
