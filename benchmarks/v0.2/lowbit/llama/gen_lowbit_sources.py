#!/usr/bin/env python3
"""Generate the lowbit kernels for the local llama.cpp measurement build.

Writes into DIR (ggml/src/ggml-cpu/): kurn.h, kurn_lowbit_<fmt>_<variant>.c for every
(format, variant) in VARIANTS (or --config JSON {fmt: {variant: {codegen keys}}}), kurn_lowbit_decl.h
(prototypes) and kurn_lowbit_dispatch.h: ggml type -> variants. The first variant of a format is the
default; GGML_KURN_<FMT>=<variant> (e.g. GGML_KURN_TQ2_0=lut) selects another at run time.

    python gen_lowbit_sources.py DIR [--config variants.json]
"""

import argparse
import json
import os
import re

from kurn import spec
from kurn.kernels import generate, kernel
from kurn.toolchain import data_path

GGML_TYPE = {"q1_0": "GGML_TYPE_Q1_0", "q2_0": "GGML_TYPE_Q2_0", "tq2_0": "GGML_TYPE_TQ2_0", "tq1_0": "GGML_TYPE_TQ1_0",
             "q2_K": "GGML_TYPE_Q2_K"}
PERIOD = {"q1_0": 128, "q2_0": 64, "tq2_0": 256, "tq1_0": 256, "q2_K": 256}
VARIANTS = {  # first = default
    "q1_0": {"lut": {"layout": "lut", "lut": "direct5", "rows": 1}, "i16": {"layout": "i16", "rows": 1},
             "lut4": {"layout": "lut", "lut": "direct4", "rows": 1}},
    "q2_0": {"i16": {"layout": "i16", "rows": 2}, "lut": {"layout": "lut", "lut": "serial5", "rows": 1}},
    "tq2_0": {"i16": {"layout": "i16", "rows": 2, "accum": "int", "prefetch": 8},
              "lut": {"layout": "lut", "lut": "serial5", "rows": 2, "prefetch": 8},
              "addsub": {"layout": "addsub", "addsub": "mask", "rows": 1}},
    "tq1_0": {"i16": {"layout": "i16", "rows": 2, "accum": "int"}, "tern": {"layout": "lut", "lut": "tern3", "rows": 1},
              "lut": {"layout": "lut", "lut": "serial4", "rows": 1}},
    "q2_K": {"k16": {"layout": "k16", "rows": 4}},
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--config")
    a = ap.parse_args()
    variants = json.load(open(a.config)) if a.config else VARIANTS
    os.makedirs(a.dir, exist_ok=True)
    with open(data_path("kurn.h")) as fh:
        open(os.path.join(a.dir, "kurn.h"), "w").write(fh.read())
    decl, rows = [], []
    for fmt, vs in variants.items():
        for name, keys in vs.items():
            c = spec.resolve({"op": "gemv", "weights": fmt, "target": "avx512_vnni", **keys})
            e = kernel(c).entry
            ne = f"{e}_{name}"
            src = re.sub(rf"\b{e}(?=_|\b)", ne, generate(c))
            src = ("#if defined(__AVX512F__) && defined(__AVX512BW__) && defined(__AVX512VNNI__)\n"
                   '#include "kurn_lowbit_decl.h"\n' + src + "#endif\n")
            open(os.path.join(a.dir, f"kurn_lowbit_{fmt}_{name}.c"), "w").write(src)
            lut = c["layout"] == "lut"
            decl.append(f"void *{ne}_prepare(const void *, int64_t, int64_t); "
                        f"void {ne}_packed(const void *, const void *, float *, int64_t, int64_t, int64_t);")
            if lut:
                decl.append(f"void {ne}_lut_info(int64_t, int64_t *, int64_t *); "
                            f"void {ne}_lut_build(const void *, int64_t, void *, int64_t, int64_t); "
                            f"void {ne}_lut_rows(const void *, const void *, float *, int64_t, int64_t, int64_t);")
            align = 32 if c["layout"] in ("lut", "addsub", "l32") else 16
            fns = f"{ne}_lut_info, {ne}_lut_build, {ne}_lut_rows" if lut else "NULL, NULL, NULL"
            rows.append(f'    {{ {GGML_TYPE[fmt]}, "{fmt}", "{name}", {PERIOD[fmt]}, {align}, {ne}_prepare, {ne}_packed, {fns} }},')
            print(fmt, name, {k: c[k] for k in ("layout", "lut", "addsub", "rows", "prefetch", "unpack", "accum") if c[k] != "auto"})
    hdr = ["// Generated by kurn benchmarks/v0.2/lowbit/llama/gen_lowbit_sources.py. Do not edit.", "#pragma once",
           "#include <stdint.h>", "#include <stddef.h>"]
    open(os.path.join(a.dir, "kurn_lowbit_decl.h"), "w").write("\n".join(hdr + decl) + "\n")
    out = [*hdr, '#include "kurn_lowbit_decl.h"',
           "typedef struct { int type; const char *fmt, *name; int64_t period, row_align;",
           "    void *(*prep)(const void *, int64_t, int64_t);",
           "    void (*packed)(const void *, const void *, float *, int64_t, int64_t, int64_t);",
           "    void (*lut_info)(int64_t, int64_t *, int64_t *);",
           "    void (*lut_build)(const void *, int64_t, void *, int64_t, int64_t);",
           "    void (*lut_rows)(const void *, const void *, float *, int64_t, int64_t, int64_t);",
           "} kurn_lowbit_kernel;", "static const kurn_lowbit_kernel kurn_lowbit_kernels[] = {", *rows, "};"]
    open(os.path.join(a.dir, "kurn_lowbit_dispatch.h"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
